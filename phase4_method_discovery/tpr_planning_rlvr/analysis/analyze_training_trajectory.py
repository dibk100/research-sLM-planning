def main() -> None:
    args = parse_args()

    if not args.csv.exists():
        raise FileNotFoundError(
            f"CSV not found: {args.csv}"
        )

    output_dir = (
        args.output_dir.resolve()
    )

    output_dir.mkdir(
        parents=True,
        exist_ok=True,
    )

    print("=" * 100)
    print("TPR Planning-RLVR Step-wise Trajectory Analysis")
    print("=" * 100)

    print(f"Input  : {args.csv}")
    print(f"Output : {output_dir}")

    df = pd.read_csv(
        args.csv
    )

    require_columns(
        df,
        [
            "step",
            "reward_mean",
            "reward_min",
            "reward_max",
            "advantage_min",
            "advantage_max",
            "entropy",
            "pg_loss",
            "grad_norm",
            "response_length_mean",
            "effective_update",
        ],
    )

    df = df.sort_values(
        "step"
    ).reset_index(
        drop=True
    )

    print(
        f"Rows   : {len(df)}"
    )

    print(
        f"Steps  : "
        f"{df['step'].min()} -> "
        f"{df['step'].max()}"
    )

    # -----------------------------------------------------------------
    # Step-wise plots
    # -----------------------------------------------------------------

    plot_single_trajectory(
        df,
        "reward_mean",
        "Mean TPR reward",
        "Step-wise TPR reward",
        output_dir
        / "01_reward_trajectory.png",
    )

    plot_single_trajectory(
        df,
        "entropy",
        "Policy entropy",
        "Step-wise policy entropy",
        output_dir
        / "02_entropy_trajectory.png",
    )

    plot_single_trajectory(
        df,
        "grad_norm",
        "Gradient norm",
        "Step-wise actor gradient norm",
        output_dir
        / "03_grad_norm_trajectory.png",
    )

    plot_single_trajectory(
        df,
        "pg_loss",
        "|Policy-gradient loss|",
        "Step-wise policy-gradient loss magnitude",
        output_dir
        / "04_pg_loss_trajectory.png",
        absolute=True,
    )

    plot_reward_and_update(
        df,
        output_dir
        / "05_reward_effective_updates.png",
    )

    plot_normalized_joint_trajectory(
        df,
        output_dir
        / "06_normalized_joint_trajectory.png",
    )

    # -----------------------------------------------------------------
    # Correlation dataframe
    # -----------------------------------------------------------------

    analysis = (
        build_analysis_dataframe(
            df
        )
    )

    analysis.to_csv(
        output_dir
        / "trajectory_metrics.csv",
        index=False,
    )

    # -----------------------------------------------------------------
    # Correlations
    # -----------------------------------------------------------------

    correlations = (
        compute_correlations(
            analysis
        )
    )

    print_correlations(
        correlations
    )

    # -----------------------------------------------------------------
    # Scatter plots
    # -----------------------------------------------------------------

    plot_scatter(
        analysis,
        "reward",
        "grad_norm",
        "Mean TPR reward",
        "Gradient norm",
        "Reward vs gradient norm",
        output_dir
        / "07_reward_vs_grad_norm.png",
    )

    plot_scatter(
        analysis,
        "reward",
        "abs_pg_loss",
        "Mean TPR reward",
        "|PG loss|",
        "Reward vs policy-gradient loss",
        output_dir
        / "08_reward_vs_pg_loss.png",
    )

    plot_scatter(
        analysis,
        "reward",
        "entropy",
        "Mean TPR reward",
        "Policy entropy",
        "Reward vs policy entropy",
        output_dir
        / "09_reward_vs_entropy.png",
    )

    plot_scatter(
        analysis,
        "advantage_range",
        "grad_norm",
        "Advantage range",
        "Gradient norm",
        "Advantage variation vs gradient norm",
        output_dir
        / "10_advantage_vs_grad_norm.png",
    )

    plot_scatter(
        analysis,
        "reward_range",
        "grad_norm",
        "Reward range",
        "Gradient norm",
        "Within-group reward variation vs gradient norm",
        output_dir
        / "11_reward_range_vs_grad_norm.png",
    )

    # -----------------------------------------------------------------
    # Update vs no-update
    # -----------------------------------------------------------------

    update_analysis = (
        update_subset_analysis(
            df,
            analysis,
        )
    )

    print_update_subset(
        update_analysis
    )

    # -----------------------------------------------------------------
    # Save JSON
    # -----------------------------------------------------------------

    summary = {
        "num_observed_steps": int(
            len(df)
        ),
        "first_step": int(
            df["step"].min()
        ),
        "last_step": int(
            df["step"].max()
        ),
        "missing_expected_steps": [
            step
            for step in range(1, 51)
            if step
            not in set(
                pd.to_numeric(
                    df["step"],
                    errors="coerce",
                )
                .dropna()
                .astype(int)
                .tolist()
            )
        ],
        "correlations": correlations,
        "update_subset_analysis": (
            update_analysis
        ),
    }

    summary_path = (
        output_dir
        / "trajectory_analysis_summary.json"
    )

    with summary_path.open(
        "w",
        encoding="utf-8",
    ) as f:
        json.dump(
            summary,
            f,
            indent=2,
            ensure_ascii=False,
        )

        f.write("\n")

    print()
    print("=" * 100)
    print("Analysis Complete")
    print("=" * 100)

    print(
        f"[Saved] "
        f"{output_dir / 'trajectory_metrics.csv'}"
    )

    print(
        f"[Saved] {summary_path}"
    )


if __name__ == "__main__":
    main()