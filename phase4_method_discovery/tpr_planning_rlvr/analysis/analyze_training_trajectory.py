def build_analysis_dataframe(
    df: pd.DataFrame,
) -> pd.DataFrame:
    analysis = pd.DataFrame()

    analysis["step"] = numeric(
        df,
        "step",
    )

    analysis["reward"] = numeric(
        df,
        "reward_mean",
    )

    analysis["entropy"] = numeric(
        df,
        "entropy",
    )

    analysis["grad_norm"] = numeric(
        df,
        "grad_norm",
    )

    analysis["abs_pg_loss"] = numeric(
        df,
        "pg_loss",
    ).abs()

    analysis["advantage_range"] = (
        numeric(
            df,
            "advantage_max",
        )
        - numeric(
            df,
            "advantage_min",
        )
    )

    analysis["response_length"] = numeric(
        df,
        "response_length_mean",
    )

    analysis["reward_range"] = (
        numeric(
            df,
            "reward_max",
        )
        - numeric(
            df,
            "reward_min",
        )
    )

    return analysis


def compute_correlations(
    analysis: pd.DataFrame,
) -> dict:
    pairs = [
        ("reward", "entropy"),
        ("reward", "grad_norm"),
        ("reward", "abs_pg_loss"),
        ("reward", "advantage_range"),
        ("reward", "response_length"),
        ("reward_range", "grad_norm"),
        ("reward_range", "abs_pg_loss"),
        ("advantage_range", "grad_norm"),
        ("advantage_range", "abs_pg_loss"),
        ("entropy", "grad_norm"),
        ("entropy", "abs_pg_loss"),
        ("step", "entropy"),
        ("step", "reward"),
        ("step", "grad_norm"),
    ]

    results = {}

    for x, y in pairs:
        key = f"{x}__vs__{y}"

        results[key] = correlation_pair(
            analysis,
            x,
            y,
        )

    return results


def print_correlations(
    correlations: dict,
) -> None:
    print()
    print("=" * 100)
    print("Correlation Analysis")
    print("=" * 100)

    print(
        f"{'Pair':<42}"
        f"{'N':>8}"
        f"{'Pearson r':>16}"
        f"{'Spearman rho':>18}"
    )

    print("-" * 84)

    for pair, result in correlations.items():
        label = pair.replace(
            "__vs__",
            " vs ",
        )

        print(
            f"{label:<42}"
            f"{result['n']:>8}"
            f"{fmt_corr(result['pearson']):>16}"
            f"{fmt_corr(result['spearman']):>18}"
        )


