def update_subset_analysis(
    original: pd.DataFrame,
    analysis: pd.DataFrame,
) -> dict:
    effective = (
        original["effective_update"]
        .astype(str)
        .str.lower()
        .map(
            {
                "true": True,
                "false": False,
                "1": True,
                "0": False,
            }
        )
        .fillna(False)
        .reset_index(drop=True)
    )

    analysis = analysis.reset_index(
        drop=True
    )

    update_df = analysis[
        effective
    ]

    no_update_df = analysis[
        ~effective
    ]

    metrics = [
        "reward",
        "entropy",
        "grad_norm",
        "abs_pg_loss",
        "advantage_range",
        "response_length",
    ]

    result = {
        "effective_update_steps": int(
            effective.sum()
        ),
        "no_update_steps": int(
            (~effective).sum()
        ),
        "metrics": {},
    }

    for metric in metrics:
        update_values = (
            update_df[metric]
            .dropna()
        )

        no_update_values = (
            no_update_df[metric]
            .dropna()
        )

        result["metrics"][metric] = {
            "update_mean": (
                float(
                    update_values.mean()
                )
                if len(update_values)
                else None
            ),
            "no_update_mean": (
                float(
                    no_update_values.mean()
                )
                if len(no_update_values)
                else None
            ),
        }

    return result


def print_update_subset(
    result: dict,
) -> None:
    print()
    print("=" * 100)
    print("Effective-update vs No-update Steps")
    print("=" * 100)

    print(
        f"Effective update : "
        f"{result['effective_update_steps']}"
    )

    print(
        f"No update        : "
        f"{result['no_update_steps']}"
    )

    print()

    print(
        f"{'Metric':<24}"
        f"{'Update mean':>18}"
        f"{'No-update mean':>20}"
    )

    print("-" * 62)

    for metric, values in result[
        "metrics"
    ].items():
        update_mean = values[
            "update_mean"
        ]

        no_update_mean = values[
            "no_update_mean"
        ]

        update_text = (
            f"{update_mean:.6f}"
            if update_mean is not None
            else "-"
        )

        no_update_text = (
            f"{no_update_mean:.6f}"
            if no_update_mean is not None
            else "-"
        )

        print(
            f"{metric:<24}"
            f"{update_text:>18}"
            f"{no_update_text:>20}"
        )


