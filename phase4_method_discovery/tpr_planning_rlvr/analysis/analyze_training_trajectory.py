def require_columns(df: pd.DataFrame, columns: list[str]) -> None:
    missing = [col for col in columns if col not in df.columns]

    if missing:
        raise ValueError(
            "Missing required columns:\n"
            + "\n".join(f"  - {col}" for col in missing)
        )


def numeric(df: pd.DataFrame, column: str) -> pd.Series:
    return pd.to_numeric(
        df[column],
        errors="coerce",
    )


def save_figure(path: Path) -> None:
    plt.tight_layout()
    plt.savefig(
        path,
        dpi=200,
        bbox_inches="tight",
    )
    plt.close()

    print(f"[Saved] {path}")


def correlation_pair(
    df: pd.DataFrame,
    x: str,
    y: str,
) -> dict:
    pair = df[[x, y]].dropna()

    if len(pair) < 3:
        return {
            "n": len(pair),
            "pearson": None,
            "spearman": None,
        }

    # pandas implements both without requiring scipy directly here.
    pearson = pair[x].corr(
        pair[y],
        method="pearson",
    )

    spearman = pair[x].corr(
        pair[y],
        method="spearman",
    )

    return {
        "n": int(len(pair)),
        "pearson": (
            float(pearson)
            if pd.notna(pearson)
            else None
        ),
        "spearman": (
            float(spearman)
            if pd.notna(spearman)
            else None
        ),
    }


def fmt_corr(value: float | None) -> str:
    if value is None:
        return "-"

    return f"{value:+.4f}"


