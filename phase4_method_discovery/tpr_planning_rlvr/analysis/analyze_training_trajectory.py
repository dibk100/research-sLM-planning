def plot_single_trajectory(
    df: pd.DataFrame,
    column: str,
    ylabel: str,
    title: str,
    output_path: Path,
    *,
    absolute: bool = False,
) -> None:
    x = numeric(df, "step")
    y = numeric(df, column)

    if absolute:
        y = y.abs()

    mask = x.notna() & y.notna()

    plt.figure(figsize=(10, 5))
    plt.plot(
        x[mask],
        y[mask],
        marker="o",
        markersize=3,
        linewidth=1.2,
    )

    plt.xlabel("Training step")
    plt.ylabel(ylabel)
    plt.title(title)
    plt.grid(
        alpha=0.25,
    )

    save_figure(output_path)


def plot_reward_and_update(
    df: pd.DataFrame,
    output_path: Path,
) -> None:
    x = numeric(df, "step")
    reward = numeric(
        df,
        "reward_mean",
    )

    effective = (
        df["effective_update"]
        .astype(str)
        .str.lower()
        .map(
            {
                "true": True,
                "false": False,
                "1": True,
                "0": False,
            }
        )
        .fillna(False)
    )

    mask = x.notna() & reward.notna()

    plt.figure(figsize=(10, 5))

    plt.plot(
        x[mask],
        reward[mask],
        marker="o",
        markersize=3,
        linewidth=1.2,
        label="Mean TPR reward",
    )

    update_mask = (
        mask
        & effective
    )

    plt.scatter(
        x[update_mask],
        reward[update_mask],
        s=45,
        marker="x",
        label="Effective update",
    )

    plt.xlabel("Training step")
    plt.ylabel("Mean TPR reward")
    plt.title(
        "TPR reward trajectory and effective policy updates"
    )

    plt.grid(
        alpha=0.25,
    )
    plt.legend()

    save_figure(output_path)


def plot_normalized_joint_trajectory(
    df: pd.DataFrame,
    output_path: Path,
) -> None:
    working = pd.DataFrame()

    working["step"] = numeric(
        df,
        "step",
    )

    working["Reward"] = numeric(
        df,
        "reward_mean",
    )

    working["Entropy"] = numeric(
        df,
        "entropy",
    )

    working["Grad norm"] = numeric(
        df,
        "grad_norm",
    )

    working["|PG loss|"] = numeric(
        df,
        "pg_loss",
    ).abs()

    normalized = pd.DataFrame(
        {
            "step": working["step"],
        }
    )

    for column in [
        "Reward",
        "Entropy",
        "Grad norm",
        "|PG loss|",
    ]:
        values = working[column]

        mu = values.mean()
        sigma = values.std(ddof=0)

        if (
            pd.isna(sigma)
            or sigma == 0
        ):
            normalized[column] = np.nan
        else:
            normalized[column] = (
                values - mu
            ) / sigma

    plt.figure(figsize=(11, 6))

    for column in [
        "Reward",
        "Entropy",
        "Grad norm",
        "|PG loss|",
    ]:
        mask = (
            normalized["step"].notna()
            & normalized[column].notna()
        )

        plt.plot(
            normalized.loc[mask, "step"],
            normalized.loc[mask, column],
            linewidth=1.3,
            label=column,
        )

    plt.axhline(
        0.0,
        linewidth=0.8,
    )

    plt.xlabel("Training step")
    plt.ylabel("Standardized value (z-score)")
    plt.title(
        "Normalized TPR training dynamics"
    )

    plt.grid(
        alpha=0.2,
    )
    plt.legend()

    save_figure(output_path)


# =============================================================================
# Scatter / correlation plots
# =============================================================================


def plot_scatter(
    df: pd.DataFrame,
    x_col: str,
    y_col: str,
    x_label: str,
    y_label: str,
    title: str,
    output_path: Path,
    *,
    x_abs: bool = False,
    y_abs: bool = False,
) -> None:
    x = numeric(
        df,
        x_col,
    )

    y = numeric(
        df,
        y_col,
    )

    if x_abs:
        x = x.abs()

    if y_abs:
        y = y.abs()

    pair = pd.DataFrame(
        {
            "x": x,
            "y": y,
        }
    ).dropna()

    plt.figure(figsize=(6.5, 5.5))

    plt.scatter(
        pair["x"],
        pair["y"],
        s=40,
        alpha=0.75,
    )

    # Least-squares line only when there is sufficient variation.
    if (
        len(pair) >= 3
        and pair["x"].nunique() >= 2
    ):
        slope, intercept = np.polyfit(
            pair["x"],
            pair["y"],
            1,
        )

        xs = np.linspace(
            pair["x"].min(),
            pair["x"].max(),
            100,
        )

        ys = (
            slope * xs
            + intercept
        )

        plt.plot(
            xs,
            ys,
            linewidth=1.2,
        )

    pearson = (
        pair["x"].corr(
            pair["y"],
            method="pearson",
        )
        if len(pair) >= 3
        else np.nan
    )

    spearman = (
        pair["x"].corr(
            pair["y"],
            method="spearman",
        )
        if len(pair) >= 3
        else np.nan
    )

    plt.xlabel(x_label)
    plt.ylabel(y_label)

    plt.title(
        f"{title}\n"
        f"Pearson r={pearson:.3f}, "
        f"Spearman ρ={spearman:.3f}"
        if pd.notna(pearson) and pd.notna(spearman)
        else title
    )

    plt.grid(
        alpha=0.2,
    )

    save_figure(output_path)


